fn emit_column(col: &Column) -> String {
    format!(
        "Column {{ name: {}, description: {}, data_type: {}, labels: {}, tests: {} }}",
        rust_string_expr(&col.name),
        emit_option_string(&col.description),
        emit_option_string(&col.data_type),
        emit_option_vec_string(&col.labels),
        emit_option_test_usages(&col.tests),
    )
}

fn emit_template_usage(usage: &TemplateUsage) -> String {
    format!(
        "TemplateUsage {{ name: {}, props: {} }}",
        rust_string_expr(&usage.name),
        emit_option_hashmap(&usage.props),
    )
}

fn emit_test_usage(usage: &TestUsage) -> String {
    format!(
        "TestUsage {{ name: {}, props: {}, sql_code: {} }}",
        rust_string_expr(&usage.name),
        emit_option_hashmap(&usage.props),
        rust_string_expr(&usage.sql_code),
    )
}

fn emit_operation_usage(usage: &OperationUsage) -> String {
    format!(
        "OperationUsage {{ name: {}, props: {}, sql_code: {} }}",
        rust_string_expr(&usage.name),
        emit_option_hashmap(&usage.props),
        rust_string_expr(&usage.sql_code),
    )
}

fn emit_option_columns(cols: &Option<Vec<Column>>) -> String {
    match cols {
        Some(cols) => format!(
            "Some(vec![{}])",
            cols.iter().map(emit_column).collect::<Vec<_>>().join(", ")
        ),
        None => "None".to_string(),
    }
}

fn emit_option_template_usage(value: &Option<TemplateUsage>) -> String {
    match value {
        Some(usage) => format!("Some({})", emit_template_usage(usage)),
        None => "None".to_string(),
    }
}

fn emit_option_test_usages(value: &Option<Vec<TestUsage>>) -> String {
    match value {
        Some(usages) => format!(
            "Some(vec![{}])",
            usages
                .iter()
                .map(emit_test_usage)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        None => "None".to_string(),
    }
}

fn emit_option_operation_usages(value: &Option<Vec<OperationUsage>>) -> String {
    match value {
        Some(usages) => format!(
            "Some(vec![{}])",
            usages
                .iter()
                .map(emit_operation_usage)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        None => "None".to_string(),
    }
}

fn emit_option_string(value: &Option<String>) -> String {
    match value {
        Some(s) => format!("Some({})", rust_string_expr(s)),
        None => "None".to_string(),
    }
}

fn emit_option_vec_string(value: &Option<Vec<String>>) -> String {
    match value {
        Some(v) => format!("Some({})", emit_vec_string(v)),
        None => "None".to_string(),
    }
}

fn emit_vec_string(values: &[String]) -> String {
    if values.is_empty() {
        "vec![]".to_string()
    } else {
        format!(
            "vec![{}]",
            values
                .iter()
                .map(|s| rust_string_expr(s))
                .collect::<Vec<_>>()
                .join(", ")
        )
    }
}

fn emit_hashmap(map: &HashMap<String, String>) -> String {
    if map.is_empty() {
        "HashMap::new()".to_string()
    } else {
        format!(
            "HashMap::from([{}])",
            map.iter()
                .map(|(k, v)| format!("({}, {})", rust_string_expr(k), rust_string_expr(v)))
                .collect::<Vec<_>>()
                .join(", ")
        )
    }
}

fn emit_option_hashmap(value: &Option<HashMap<String, String>>) -> String {
    match value {
        Some(map) => format!("Some({})", emit_hashmap(map)),
        None => "None".to_string(),
    }
}

fn rust_string_literal(s: &str) -> String {
    let mut out = String::from('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn rust_string_expr(s: &str) -> String {
    format!("{}.to_string()", rust_string_literal(s))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn minimal_entities() -> Vec<(PathBuf, Entity)> {
        vec![
            (
                PathBuf::from("config.md"),
                Entity::Config(Config {
                    props: HashMap::from([("environment".to_string(), "test".to_string())]),
                }),
            ),
            (
                PathBuf::from("model.md"),
                Entity::Model(Model {
                    name: "m".to_string(),
                    description: None,
                    tags: None,
                    table_id: None,
                    managed: false,
                    disabled: false,
                    meta: None,
                    default_transformation: None,
                }),
            ),
            (
                PathBuf::from("transformation.md"),
                Entity::Transformation(Transformation {
                    name: "m__default_transformation".to_string(),
                    sql_code: "SELECT 1".to_string(),
                    model: "m".to_string(),
                    dependent_tables: vec![],
                    used_variables: None,
                    template: None,
                    columns: None,
                    tests: None,
                    pre_runs: None,
                    post_runs: None,
                    init_runs: None,
                }),
            ),
        ]
    }

    #[test]
    fn omits_unused_usage_imports() {
        let source = emit_catalog_rs(&minimal_entities(), &Config::default()).unwrap();
        assert!(!source.contains("TestUsage"));
        assert!(!source.contains("OperationUsage"));
        assert!(!source.contains("TemplateUsage"));
        assert!(!source.contains("Column"));
    }

    #[test]
    fn includes_test_usage_import_when_needed() {
        let mut entities = minimal_entities();
        if let Entity::Transformation(t) = &mut entities[2].1 {
            t.tests = Some(vec![TestUsage {
                name: "t".to_string(),
                props: None,
                sql_code: "SELECT 1".to_string(),
            }]);
        }
        let source = emit_catalog_rs(&entities, &Config::default()).unwrap();
        assert!(source.contains("TestUsage"));
    }
}
